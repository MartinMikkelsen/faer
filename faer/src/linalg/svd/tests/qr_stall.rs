#[test]
fn test_issue81_complex_qr_stall() {
	fn check<T: ComplexField>(a: Mat<T>) {
		let expected = [
			3.9414676652919867,
			3.9414676652919858,
			0.48150883185813453,
			0.48150883185813415,
			0.11330659717393496,
			0.11330659717393492,
			0.011919830114133985,
			0.011919830114133898,
			2.8733257864429986e-17,
			7.8282169309112482e-18,
		];
		for scale in [1.0, 2.0, 1e-8, 1e8] {
			let a = Mat::<T>::from_fn(12, 10, |i, j| {
				a[(i, j)].mul_real(from_f64::<T::Real>(scale))
			});
			for adjoint in [false, true] {
				let a = if adjoint {
					a.adjoint().to_owned()
				} else {
					a.clone()
				};
				let (m, n) = a.shape();
				for threshold in [128, usize::MAX] {
					let mut params = Spec::<SvdParams, T>::default();
					params.recursion_threshold = threshold;
					for (want_u, want_v) in [
						(true, true),
						(true, false),
						(false, true),
						(false, false),
					] {
						let vectors = |want| {
							if want {
								ComputeSvdVectors::Thin
							} else {
								ComputeSvdVectors::No
							}
						};
						let mut s = Col::<T>::zeros(10);
						let mut u = Mat::<T>::zeros(m, 10);
						let mut v = Mat::<T>::zeros(n, 10);
						let mut mem = MemBuffer::new(svd_scratch::<T>(
							m,
							n,
							vectors(want_u),
							vectors(want_v),
							ParShape::Seq,
							params,
						));
						svd(
							a.as_ref(),
							s.as_mut().as_diagonal_mut(),
							if want_u { Some(u.as_mut()) } else { None },
							if want_v { Some(v.as_mut()) } else { None },
							Par::Seq,
							MemStack::new(&mut mem),
							params,
						)
						.unwrap();
						assert!(s.is_all_finite());
						let tol = from_f64::<T::Real>(64.0 * m.max(n) as f64)
							* eps::<T::Real>();
						for i in 0..10 {
							assert_eq!(s[i].imag(), zero::<T::Real>());
							assert!(s[i].real() >= zero::<T::Real>());
							if i > 0 {
								assert!(s[i - 1].real() >= s[i].real());
							}
							let value =
								s[i].real() / from_f64::<T::Real>(scale);
							assert!(
								(value - from_f64::<T::Real>(expected[i]))
									.abs() <= &tol
									* from_f64::<T::Real>(expected[0])
							);
						}
						if want_u {
							assert!(
								(u.adjoint() * &u - Mat::<T>::identity(10, 10))
									.norm_max() <= tol
							);
						}
						if want_v {
							assert!(
								(v.adjoint() * &v - Mat::<T>::identity(10, 10))
									.norm_max() <= tol
							);
						}
						if want_u && want_v {
							let back = &u * s.as_diagonal() * v.adjoint();
							assert!(
								(&back - &a).norm_l2() / a.norm_l2() <= tol
							);
						}
					}
				}
			}
		}
	}
	check(issue81_matrix::<c64>(c64::new));
	check(issue81_matrix::<c32>(|re, im| {
		c32::new(re as f32, im as f32)
	}));
}
